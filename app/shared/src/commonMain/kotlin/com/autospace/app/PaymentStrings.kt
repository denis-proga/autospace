/** Язык определяется по самим строкам интерфейса, поэтому не зависит от формата кода языка. */
internal fun paymentStrings(strings: AppStrings): PaymentStrings = when (strings.botGreeting) {
    EnglishStrings.botGreeting -> PayEn
    SpanishStrings.botGreeting -> PayEs
    GermanStrings.botGreeting -> PayDe
    UkrainianStrings.botGreeting -> PayUk
    else -> PayRu
}
