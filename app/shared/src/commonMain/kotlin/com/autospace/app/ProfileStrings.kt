/** Язык определяется по самим строкам интерфейса, поэтому не зависит от формата кода языка. */
internal fun profileStrings(strings: AppStrings): ProfileStrings = when (strings.botGreeting) {
    EnglishStrings.botGreeting -> ProfEn
    SpanishStrings.botGreeting -> ProfEs
    GermanStrings.botGreeting -> ProfDe
    UkrainianStrings.botGreeting -> ProfUk
    else -> ProfRu
}
